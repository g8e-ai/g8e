#!/usr/bin/env python3

"""Generate or verify ``g8e/enums.pyi`` from the runtime-built protocol enums.

``g8e.enums`` builds its enums dynamically from the protocol constant JSON, so
static analyzers need a stub. Members are emitted as literal assignments so
Pyright types ``OperatorToolName.RUN_COMMANDS`` as the enum member, not ``str``.
"""

from __future__ import annotations

import argparse
import importlib
import sys
from enum import IntEnum
from pathlib import Path

PYTHON_ROOT = Path(__file__).resolve().parents[1]
STUB_PATH = PYTHON_ROOT / "g8e" / "enums.pyi"

# Acronym spellings that ``g8e.enums.__getattr__`` resolves to the same category
# as the canonical ``__all__`` name; consumers import these spellings directly.
ACRONYM_ALIASES: dict[str, str] = {
    "AISource": "AiSource",
    "AITaskId": "AiTaskId",
}

HEADER = '''# Copyright (c) 2026 Lateralus Labs, LLC.
# Use of this source code is governed by the Business Source License
# included in the LICENSE file.
#
# As of the Change Date listed in the LICENSE file, this software is
# released under the Apache License, Version 2.0.

# Code generated by protocol/python/scripts/generate_enum_stubs.py. DO NOT EDIT.

"""Type stubs for dynamically-generated protocol enums."""

from enum import IntEnum, StrEnum
from typing import Any

__all__: list[str]

class CaseInsensitiveStrEnum(StrEnum):
    @classmethod
    def _missing_(cls, value: object) -> Any: ...
'''


def render() -> str:
    sys.path.insert(0, str(PYTHON_ROOT))
    enums = importlib.import_module("g8e.enums")

    blocks = [HEADER]
    for name in sorted(set(enums.__all__)):
        cls = getattr(enums, name)
        base = "IntEnum" if issubclass(cls, IntEnum) else "CaseInsensitiveStrEnum"
        lines = [f"\nclass {name}({base}):"]
        for member in cls:
            lines.append(f"    {member.name} = {member.value!r}")
        blocks.append("\n".join(lines) + "\n")
    blocks.append("".join(f"{alias} = {name}\n" for alias, name in ACRONYM_ALIASES.items()))
    return "\n".join(blocks)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the stub is stale")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        if not STUB_PATH.exists() or STUB_PATH.read_text() != rendered:
            print(f"{STUB_PATH} is stale; run make proto-generate", file=sys.stderr)
            return 1
        return 0
    STUB_PATH.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
