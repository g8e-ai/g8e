"""
Generate Python constants from protocol/constants/*.json files.
This script reads the JSON source of truth and emits Python constants.
"""

import json
import os
import sys
from pathlib import Path
from typing import Any, Dict


def load_json_file(filepath: Path) -> Dict[str, Any]:
    """Load and parse a JSON file."""
    with open(filepath, 'r') as f:
        return json.load(f)


def to_snake_case(name: str) -> str:
    """Convert PascalCase or camelCase to snake_case."""
    result = []
    for i, c in enumerate(name):
        if c.isupper() and i > 0:
            result.append('_')
        result.append(c.lower())
    return ''.join(result)


def generate_headers(headers_data: Dict[str, Any]) -> str:
    """Generate Python header constants from headers.json."""
    output = []
    
    output.append("# Copyright (c) 2026 Lateralus Labs, LLC.")
    output.append("# Licensed under the Apache License, Version 2.0 (the \"License\");")
    output.append("# you may not use this file except in compliance with the License.")
    output.append("# You may obtain a copy of the License at")
    output.append("#")
    output.append("#     http://www.apache.org/licenses/LICENSE-2.0")
    output.append("#")
    output.append("# Unless required by applicable law or agreed to in writing, software")
    output.append("# distributed under the License is distributed on an \"AS IS\" BASIS,")
    output.append("# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.")
    output.append("# See the License for the specific language governing permissions and")
    output.append("# limitations under the License.")
    output.append("")
    output.append("# Code generated by generate_constants.py. DO NOT EDIT.")
    output.append("# Source: protocol/constants/headers.json")
    output.append("# To regenerate: python app/constants/generate_constants.py")
    output.append("")
    
    # Generate individual constants
    for key, entry in sorted(headers_data.items()):
        python_const = entry.get('_python_const')
        value = entry.get('value')
        if python_const and value:
            output.append(f"{python_const} = \"{value}\"")
    
    output.append("")
    
    # Generate G8eHeaders class
    output.append("class G8eHeaders:")
    output.append('    """Collection of canonical G8E header names."""')
    for key, entry in sorted(headers_data.items()):
        python_const = entry.get('_python_const')
        value = entry.get('value')
        if python_const and value:
            # Convert to class attribute name (same as constant name)
            attr_name = python_const
            output.append(f"    {attr_name} = \"{value}\"")
    
    return '\n'.join(output)


def generate_status(status_data: Dict[str, Dict[str, Any]]) -> str:
    """Generate Python status enums from status.json."""
    output = []
    
    output.append("# Copyright (c) 2026 Lateralus Labs, LLC.")
    output.append("# Licensed under the Apache License, Version 2.0 (the \"License\");")
    output.append("# you may not use this file except in compliance with the License.")
    output.append("# You may obtain a copy of the License at")
    output.append("#")
    output.append("#     http://www.apache.org/licenses/LICENSE-2.0")
    output.append("#")
    output.append("# Unless required by applicable law or agreed to in writing, software")
    output.append("# distributed under the License is distributed on an \"AS IS\" BASIS,")
    output.append("# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.")
    output.append("# See the License for the specific language governing permissions and")
    output.append("# limitations under the License.")
    output.append("")
    output.append("# Code generated by generate_constants.py. DO NOT EDIT.")
    output.append("# Source: protocol/constants/status.json")
    output.append("# To regenerate: python app/constants/generate_constants.py")
    output.append("")
    output.append("from enum import StrEnum")
    output.append("")
    
    # Generate enum classes for each category
    for category, entries in sorted(status_data.items()):
        # Convert category to class name (e.g., "user_role" -> "UserRole")
        class_name = ''.join(word.capitalize() for word in category.replace('.', '_').split('_'))
        
        output.append(f"class {class_name}(StrEnum):")
        output.append(f'    """Generated from protocol/constants/status.json - {category}"""')
        
        for key, entry in sorted(entries.items()):
            python_const = entry.get('_python_const')
            value = entry.get('value')
            if python_const and value:
                output.append(f"    {python_const} = \"{value}\"")
        
        output.append("")
    
    return '\n'.join(output)


def main():
    """Main entry point."""
    # Determine paths
    script_dir = Path(__file__).parent
    protocol_constants_dir = script_dir / ".." / ".." / ".." / ".." / "protocol" / "constants"
    protocol_constants_dir = protocol_constants_dir.resolve()
    
    # Load headers.json
    headers_file = protocol_constants_dir / "headers.json"
    headers_data = load_json_file(headers_file).get('headers', {})
    
    # Load status.json
    status_file = protocol_constants_dir / "status.json"
    status_data = load_json_file(status_file).get('status', {})
    
    # Generate headers
    headers_output = generate_headers(headers_data)
    headers_output_path = script_dir / "headers_generated.py"
    with open(headers_output_path, 'w') as f:
        f.write(headers_output)
    
    # Generate status
    status_output = generate_status(status_data)
    status_output_path = script_dir / "status_generated.py"
    with open(status_output_path, 'w') as f:
        f.write(status_output)
    
    print(f"Successfully generated headers_generated.py and status_generated.py from JSON source files")


if __name__ == "__main__":
    main()
