//go:build windows

package mcp

import (
	"os/exec"
	"syscall"
)

const subprocessCreateNewProcessGroup = 0x00000200

func setSubprocessSysProcAttr(cmd *exec.Cmd) {
	if cmd.SysProcAttr == nil {
		cmd.SysProcAttr = &syscall.SysProcAttr{}
	}
	cmd.SysProcAttr.CreationFlags = subprocessCreateNewProcessGroup
}
