func TestLoadActionTypeMeta_ReadsGoConstValueAndClassificationFlags(t *testing.T) {
	path := filepath.Join(t.TempDir(), "status.json")
	writeFile(t, path, `{
		"status": {
			"action_type": {
				"FS_READ":      {"_go_const": "ActionFSRead",  "value": "FS_READ"},
				"FS_WRITE":     {"_go_const": "ActionFSWrite", "value": "FS_WRITE", "_mutation": true},
				"ENROLL":       {"_go_const": "ActionEnroll",  "value": "ENROLL", "_bootstrap": true},
				"REGISTER_KEY": {"_go_const": "ActionKey",     "value": "REGISTER_KEY", "_mutation": true, "_bootstrap": true}
			},
			"unrelated": {"ignored": {"value": "x"}}
		}
	}`)

	got, err := loadActionTypeMeta(path)

	require.NoError(t, err)
	assert.Equal(t, map[string]actionTypeMeta{
		"FS_READ":      {GoConst: "ActionFSRead", Value: "FS_READ"},
		"FS_WRITE":     {GoConst: "ActionFSWrite", Value: "FS_WRITE", Mutation: true},
		"ENROLL":       {GoConst: "ActionEnroll", Value: "ENROLL", Bootstrap: true},
		"REGISTER_KEY": {GoConst: "ActionKey", Value: "REGISTER_KEY", Mutation: true, Bootstrap: true},
	}, got)
}

func TestLoadActionTypeMeta_ReturnsEmptyMapWhenStatusHasNoActionTypes(t *testing.T) {
	path := filepath.Join(t.TempDir(), "status.json")
	writeFile(t, path, `{"status":{}}`)

	got, err := loadActionTypeMeta(path)

	require.NoError(t, err)
	assert.NotNil(t, got)
	assert.Empty(t, got)
}

func TestLoadActionTypeMeta_ReportsMissingAndMalformedFiles(t *testing.T) {
	t.Run("missing file", func(t *testing.T) {
		_, err := loadActionTypeMeta(filepath.Join(t.TempDir(), "absent.json"))

		require.Error(t, err)
		assert.ErrorIs(t, err, os.ErrNotExist)
	})
	t.Run("malformed json names the file", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "status.json")
		writeFile(t, path, `{"status": `)

		_, err := loadActionTypeMeta(path)

		require.Error(t, err)
		assert.Contains(t, err.Error(), "decode "+path)
	})
	t.Run("flag with wrong type", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "status.json")
		writeFile(t, path, `{"status":{"action_type":{"X":{"_mutation":"yes"}}}}`)

		_, err := loadActionTypeMeta(path)

		require.Error(t, err)
		assert.Contains(t, err.Error(), "decode "+path)
	})
}

