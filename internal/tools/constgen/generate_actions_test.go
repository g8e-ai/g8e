func sampleActionTypes() map[string]actionTypeMeta {
	return map[string]actionTypeMeta{
		"B_MUTATE":   {GoConst: "ActionBMutate", Value: "B_MUTATE", Mutation: true},
		"A_BOOT":     {GoConst: "ActionABoot", Value: "A_BOOT", Bootstrap: true},
		"C_BOTH":     {GoConst: "ActionCBoth", Value: "C_BOTH", Mutation: true, Bootstrap: true},
		"D_READONLY": {GoConst: "ActionDReadonly", Value: "D_READONLY"},
	}
}

func TestGenerateActionTypesGo_DeclaresTypedConstantsSortedByRegistryKey(t *testing.T) {
	got, err := generateActionTypesGo(sampleActionTypes())

	require.NoError(t, err)
	requireParsesAsGo(t, got)
	assert.Contains(t, got, "// Code generated by constgen; DO NOT EDIT.")
	assert.Contains(t, got, "type ActionType string")
	assert.Contains(t, got, "\tActionABoot ActionType = \"A_BOOT\"\n\tActionBMutate ActionType = \"B_MUTATE\"\n\tActionCBoth ActionType = \"C_BOTH\"\n\tActionDReadonly ActionType = \"D_READONLY\"\n")
}

func TestGenerateActionTypesGo_AllActionTypesListsEveryConstantInKeyOrder(t *testing.T) {
	got, err := generateActionTypesGo(sampleActionTypes())

	require.NoError(t, err)
	assert.Contains(t, got, "var AllActionTypes = []ActionType{\n\tActionABoot,\n\tActionBMutate,\n\tActionCBoth,\n\tActionDReadonly,\n}\n")
}

func TestGenerateActionTypesGo_IsMutationCoversOnlyMutationFlaggedActions(t *testing.T) {
	got, err := generateActionTypesGo(sampleActionTypes())

	require.NoError(t, err)
	mutation := between(t, got, "func (a ActionType) IsMutation() bool {", "func (a ActionType) IsBootstrapAction() bool {")
	assert.Contains(t, mutation, "case ActionBMutate,\n\t\tActionCBoth:\n\t\treturn true\n\tdefault:\n\t\treturn false")
	assert.NotContains(t, mutation, "ActionABoot")
	assert.NotContains(t, mutation, "ActionDReadonly")
}

func TestGenerateActionTypesGo_IsBootstrapActionCoversOnlyBootstrapFlaggedActions(t *testing.T) {
	got, err := generateActionTypesGo(sampleActionTypes())

	require.NoError(t, err)
	bootstrap := got[strings.Index(got, "func (a ActionType) IsBootstrapAction() bool {"):]
	assert.Contains(t, bootstrap, "case ActionABoot,\n\t\tActionCBoth:\n\t\treturn true\n\tdefault:\n\t\treturn false")
	assert.NotContains(t, bootstrap, "ActionBMutate")
	assert.NotContains(t, bootstrap, "ActionDReadonly")
}

func TestGenerateActionTypesGo_IsDeterministicAcrossMapIterationOrder(t *testing.T) {
	first, err := generateActionTypesGo(sampleActionTypes())
	require.NoError(t, err)
	for range 20 {
		again, err := generateActionTypesGo(sampleActionTypes())
		require.NoError(t, err)
		require.Equal(t, first, again)
	}
}

// between returns the text of s from the first occurrence of start up to, but
// excluding, the first occurrence of end that follows it.
func between(t *testing.T, s, start, end string) string {
	t.Helper()
	from := strings.Index(s, start)
	require.GreaterOrEqual(t, from, 0, "missing %q", start)
	rest := s[from:]
	to := strings.Index(rest, end)
	require.GreaterOrEqual(t, to, 0, "missing %q after %q", end, start)
	return rest[:to]
}
