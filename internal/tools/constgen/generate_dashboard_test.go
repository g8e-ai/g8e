func TestGenerateDashboardEventsJS_OmitsAbsentOptionalFieldsAndMarksReservedEvents(t *testing.T) {
	got, err := generateDashboardEventsJS(dashboardFixture())

	require.NoError(t, err)
	registry := got[strings.Index(got, "export const EventRegistry"):]
	caseCreated := between(t, registry, "    APP_CASE_CREATED: Object.freeze({", "    }),")
	assert.NotContains(t, caseCreated, "transport:")
	assert.NotContains(t, caseCreated, "producers:")
	assert.NotContains(t, caseCreated, "actionType:")
	assert.NotContains(t, caseCreated, "payload:")
	assert.Contains(t, caseCreated, "reserved: true,")

	command := between(t, registry, "    OPERATOR_COMMAND_REQUESTED: Object.freeze({", "    }),")
	assert.NotContains(t, command, "reserved:")
}

