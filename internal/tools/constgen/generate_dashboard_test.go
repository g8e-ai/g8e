func TestGenerateDashboardEventsJS_IsDeterministicAcrossMapIterationOrder(t *testing.T) {
	first, err := generateDashboardEventsJS(dashboardFixture())
	require.NoError(t, err)
	for range 20 {
		again, err := generateDashboardEventsJS(dashboardFixture())
		require.NoError(t, err)
		require.Equal(t, first, again)
	}
}
