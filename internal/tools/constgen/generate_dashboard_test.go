func TestRegistryKeyToJSEnum_SplitsPascalCaseIntoUpperSnakeCase(t *testing.T) {
	tests := []struct {
		name string
		key  string
		want string
	}{
		{name: "empty key", key: "", want: ""},
		{name: "single upper letter", key: "A", want: "A"},
		{name: "single word", key: "Heartbeat", want: "HEARTBEAT"},
		{name: "two words", key: "CaseCreated", want: "CASE_CREATED"},
		{name: "three words", key: "OperatorCommandRequested", want: "OPERATOR_COMMAND_REQUESTED"},
		{name: "acronym followed by word stays together until the last capital", key: "HTTPServerStarted", want: "HTTP_SERVER_STARTED"},
		{name: "trailing acronym is not split", key: "OperatorMCP", want: "OPERATOR_MCP"},
		{name: "digit followed by capital splits", key: "Tier1Result", want: "TIER1_RESULT"},
		{name: "lowercase followed by digit does not split", key: "Sha256Computed", want: "SHA256_COMPUTED"},
		{name: "already upper snake is unchanged apart from case", key: "ALREADY_UPPER", want: "ALREADY_UPPER"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, registryKeyToJSEnum(tt.key))
		})
	}
}

func TestShouldSplitPascal_BoundariesBetweenCharacterClasses(t *testing.T) {
	tests := []struct {
		name  string
		input string
		index int
		want  bool
	}{
		{name: "lower to upper", input: "aB", index: 1, want: true},
		{name: "digit to upper", input: "1B", index: 1, want: true},
		{name: "upper to lower", input: "Ab", index: 1, want: false},
		{name: "upper to upper before lower splits the acronym boundary", input: "ABc", index: 1, want: true},
		{name: "upper to upper at end of input", input: "AB", index: 1, want: false},
		{name: "upper to upper before upper", input: "ABC", index: 1, want: false},
		{name: "lower to lower", input: "ab", index: 1, want: false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, shouldSplitPascal([]rune(tt.input), tt.index))
		})
	}
}

