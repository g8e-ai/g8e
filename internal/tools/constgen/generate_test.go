func TestWriteGenerated_WritesEveryTargetAndSyncsBundledPythonRegistry(t *testing.T) {
	root := newConstgenRoot(t)
	out := sampleOutputs()

	require.NoError(t, writeGenerated(root, out))

	for rel, want := range map[string]string{
		eventsGoRel:      out.EventsGo,
		actionTypesGoRel: out.ActionTypesGo,
		consoleTSRel:   out.ConsoleTS,
	} {
		got, err := os.ReadFile(filepath.Join(root, rel))
		require.NoError(t, err, rel)
		assert.Equal(t, want, string(got), rel)
	}
	canonical, err := os.ReadFile(filepath.Join(root, eventsRel))
	require.NoError(t, err)
	bundled, err := os.ReadFile(filepath.Join(root, pythonEventsRel))
	require.NoError(t, err)
	assert.Equal(t, canonical, bundled)
}

