func generateDashboardEventsJS(reg registryFile) (string, error) {
	keys := sortedEventKeys(reg.Events)

	var b strings.Builder
	b.WriteString(`// Copyright (c) 2026 Lateralus Labs, LLC.
// Licensed under the Business Source License 1.1 — see LICENSE for details.

// Code generated by constgen; DO NOT EDIT.

export const EventType = Object.freeze({
`)
	for _, key := range keys {
		entry := reg.Events[key]
		member := registryKeyToJSEnum(key)
		fmt.Fprintf(&b, "    %s: '%s',\n", member, entry.Value)
	}
	b.WriteString(`});

export const EventRegistry = Object.freeze({
`)
	for _, key := range keys {
		entry := reg.Events[key]
		member := registryKeyToJSEnum(key)
		fmt.Fprintf(&b, "    %s: Object.freeze({\n", member)
		fmt.Fprintf(&b, "        kind: '%s',\n", entry.Kind)
		if len(entry.Transport) > 0 {
			quoted := make([]string, len(entry.Transport))
			for i, t := range entry.Transport {
				quoted[i] = fmt.Sprintf("'%s'", t)
			}
			fmt.Fprintf(&b, "        transport: [%s],\n", strings.Join(quoted, ", "))
		}
		if len(entry.Producers) > 0 {
			quoted := make([]string, len(entry.Producers))
			for i, p := range entry.Producers {
				quoted[i] = fmt.Sprintf("'%s'", p)
			}
			fmt.Fprintf(&b, "        producers: [%s],\n", strings.Join(quoted, ", "))
		}
		fmt.Fprintf(&b, "        persistence: '%s',\n", entry.Persistence)
		if entry.Governance != nil {
			fmt.Fprintf(&b, "        actionType: '%s',\n", entry.Governance.ActionType)
			fmt.Fprintf(&b, "        payload: '%s',\n", entry.Governance.Payload)
		}
		if entry.Reserved {
			b.WriteString("        reserved: true,\n")
		}
		b.WriteString("    }),\n")
	}
	b.WriteString(`});
`)
	return b.String(), nil
}

func registryKeyToJSEnum(key string) string {
	runes := []rune(key)
	var b strings.Builder
	for i, r := range runes {
		if i > 0 && shouldSplitPascal(runes, i) {
			b.WriteByte('_')
		}
		b.WriteRune(r)
	}
	return strings.ToUpper(b.String())
}

func shouldSplitPascal(runes []rune, i int) bool {
	prev := runes[i-1]
	curr := runes[i]
	if (unicode.IsLower(prev) || unicode.IsDigit(prev)) && unicode.IsUpper(curr) {
		return true
	}
	return unicode.IsUpper(prev) && unicode.IsUpper(curr) && i+1 < len(runes) && unicode.IsLower(runes[i+1])
}
