func TestGenerateEventsGo_AppendsOperatorHierarchyAfterRegistry(t *testing.T) {
	reg, actionTypes := eventsFixture()
	hierarchy := map[string]string{"EventOperatorCommandRequested": "Command.Requested"}

	got, err := generateEventsGo(reg, hierarchy, actionTypes)

	require.NoError(t, err)
	requireParsesAsGo(t, got)
	registryEnd := strings.Index(got, "}}\n\n")
	hierarchyStart := strings.Index(got, "type _EventOperator struct {")
	require.GreaterOrEqual(t, registryEnd, 0)
	require.Greater(t, hierarchyStart, registryEnd)
	assert.Contains(t, got, "Requested: EventOperatorCommandRequested,")
}

