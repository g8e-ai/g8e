func TestTitleCase_UppercasesOnlyTheFirstByte(t *testing.T) {
	tests := []struct {
		name  string
		input string
		want  string
	}{
		{name: "empty", input: "", want: ""},
		{name: "lowercase word", input: "request", want: "Request"},
		{name: "already capitalised", input: "Outcome", want: "Outcome"},
		{name: "rest of the word is left alone", input: "sTREAM", want: "STREAM"},
		{name: "single letter", input: "f", want: "F"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, titleCase(tt.input))
		})
	}
}

func TestGoStringSlice_RendersNilForEmptyAndQuotedLiteralOtherwise(t *testing.T) {
	tests := []struct {
		name   string
		values []string
		want   string
	}{
		{name: "nil slice", values: nil, want: "nil"},
		{name: "empty slice", values: []string{}, want: "nil"},
		{name: "single value", values: []string{"gateway"}, want: `[]string{"gateway"}`},
		{name: "multiple values keep order", values: []string{"sse", "pubsub"}, want: `[]string{"sse", "pubsub"}`},
		{name: "quotes and backslashes are escaped", values: []string{`a"b`, `c\d`}, want: `[]string{"a\"b", "c\\d"}`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, goStringSlice(tt.values))
		})
	}
}

