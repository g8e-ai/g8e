func TestGenerateEventsGo_IsDeterministicAcrossMapIterationOrder(t *testing.T) {
	reg, actionTypes := eventsFixture()
	hierarchy := map[string]string{
		"EventOperatorCommandRequested": "Command.Requested",
		"EventOperatorCommandCompleted": "Command.Completed",
		"EventOperatorHeartbeat":        "Heartbeat",
	}
	first, err := generateEventsGo(reg, hierarchy, actionTypes)
	require.NoError(t, err)

	for range 20 {
		again, err := generateEventsGo(reg, hierarchy, actionTypes)
		require.NoError(t, err)
		require.Equal(t, first, again)
	}
}

func TestGenerateOperatorHierarchy_NestsStructsByPathAndKeepsLeavesAsEventTypes(t *testing.T) {
	hierarchy := map[string]string{
		"EventOperatorCommandRequested": "Command.Requested",
		"EventOperatorCommandCompleted": "Command.Completed",
		"EventOperatorHeartbeat":        "Heartbeat",
	}

	got := generateOperatorHierarchy(hierarchy)

	want := "type _EventOperator struct {\n" +
		"\tCommand _EventOperatorCommand\n" +
		"\tHeartbeat EventType\n" +
		"}\n\n" +
		"type _EventOperatorCommand struct {\n" +
		"\tCompleted EventType\n" +
		"\tRequested EventType\n" +
		"}\n\n" +
		"var Event = struct {\n" +
		"\tOperator _EventOperator\n" +
		"}{\n" +
		"\tOperator: _EventOperator{\n" +
		"\t\tCommand: _EventOperatorCommand{\n" +
		"\t\t\tCompleted: EventOperatorCommandCompleted,\n" +
		"\t\t\tRequested: EventOperatorCommandRequested,\n" +
		"\t\t},\n" +
		"\t\tHeartbeat: EventOperatorHeartbeat,\n" +
		"\t},\n" +
		"}\n"
	assert.Equal(t, want, got)
}

func TestGenerateOperatorHierarchy_SupportsMoreThanTwoLevelsOfNesting(t *testing.T) {
	hierarchy := map[string]string{
		"EventOperatorAuditUserRecordRequested": "Audit.User.Record.Requested",
		"EventOperatorAuditUserRecordCreated":   "Audit.User.Record.Created",
		"EventOperatorAuditSystemRecorded":      "Audit.System.Recorded",
	}

	got := generateOperatorHierarchy(hierarchy)

	requireParsesAsGo(t, "package constants\ntype EventType string\n"+got)
	for _, typeDecl := range []string{
		"type _EventOperator struct {\n\tAudit _EventOperatorAudit\n}\n",
		"type _EventOperatorAudit struct {\n\tSystem _EventOperatorAuditSystem\n\tUser _EventOperatorAuditUser\n}\n",
		"type _EventOperatorAuditSystem struct {\n\tRecorded EventType\n}\n",
		"type _EventOperatorAuditUser struct {\n\tRecord _EventOperatorAuditUserRecord\n}\n",
		"type _EventOperatorAuditUserRecord struct {\n\tCreated EventType\n\tRequested EventType\n}\n",
	} {
		assert.Contains(t, got, typeDecl)
	}
	assert.Contains(t, got, "\t\t\t\t\tCreated: EventOperatorAuditUserRecordCreated,\n")
}
