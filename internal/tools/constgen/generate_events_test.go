func TestActionTypeGoConst_ResolvesByWireValueNotRegistryKey(t *testing.T) {
	actionTypes := map[string]actionTypeMeta{
		"KEY_A": {GoConst: "ActionA", Value: "A_WIRE"},
		"KEY_B": {GoConst: "ActionB", Value: "B_WIRE"},
	}

	got, err := actionTypeGoConst(actionTypes, "B_WIRE")
	require.NoError(t, err)
	assert.Equal(t, "ActionB", got)

	_, err = actionTypeGoConst(actionTypes, "KEY_B")
	require.Error(t, err, "registry key must not resolve; only the wire value does")
	assert.Contains(t, err.Error(), `unknown governance.action_type "KEY_B"`)
}

func eventsFixture() (registryFile, map[string]actionTypeMeta) {
	reg := registryFile{Events: map[string]eventEntry{
		"OperatorCommandRequested": {
			GoConst:     "EventOperatorCommandRequested",
			Value:       "g8e.v1.operator.command.requested",
			Kind:        "request",
			Transport:   []string{"governed"},
			Producers:   []string{"gateway", "ensemble"},
			Persistence: "operator.audit_log",
			Outcomes:    []string{"OperatorCommandCompleted"},
			Governance:  &governanceBlock{ActionType: "EXECUTE_BASH", Payload: "g8e.operator.v1.CommandRequested"},
		},
		"OperatorCommandCompleted": {
			GoConst:     "EventOperatorCommandCompleted",
			Value:       "g8e.v1.operator.command.completed",
			Kind:        "outcome",
			Producers:   []string{"operator"},
			Persistence: "operator.audit_log",
			Reserved:    true,
		},
	}}
	actionTypes := map[string]actionTypeMeta{
		"EXECUTE_BASH": {GoConst: "ActionExecuteBash", Value: "EXECUTE_BASH", Mutation: true},
	}
	return reg, actionTypes
}

func TestGenerateEventsGo_DeclaresOneTypedConstantPerEventSortedByRegistryKey(t *testing.T) {
	reg, actionTypes := eventsFixture()

	got, err := generateEventsGo(reg, map[string]string{}, actionTypes)

	require.NoError(t, err)
	requireParsesAsGo(t, got)
	assert.Contains(t, got, "// Code generated by constgen; DO NOT EDIT.")
	assert.Contains(t, got, "type EventType string")
	completed := strings.Index(got, `const EventOperatorCommandCompleted EventType = "g8e.v1.operator.command.completed"`)
	requested := strings.Index(got, `const EventOperatorCommandRequested EventType = "g8e.v1.operator.command.requested"`)
	require.GreaterOrEqual(t, completed, 0)
	require.GreaterOrEqual(t, requested, 0)
	assert.Less(t, completed, requested, "OperatorCommandCompleted sorts before OperatorCommandRequested")
}

func TestGenerateEventsGo_RegistryEntryCarriesGovernanceTransportAndOutcomes(t *testing.T) {
	reg, actionTypes := eventsFixture()

	got, err := generateEventsGo(reg, map[string]string{}, actionTypes)

	require.NoError(t, err)
	entry := between(t, got, "\tEventOperatorCommandRequested: {\n", "\t},\n")
	assert.Contains(t, entry, `Key: "OperatorCommandRequested",`)
	assert.Contains(t, entry, "Kind: EventKindRequest,")
	assert.Contains(t, entry, `Transport: []string{"governed"},`)
	assert.Contains(t, entry, `Producers: []string{"gateway", "ensemble"},`)
	assert.Contains(t, entry, `Persistence: "operator.audit_log",`)
	assert.Contains(t, entry, "GovernanceAction: ActionExecuteBash,")
	assert.Contains(t, entry, `GovernancePayload: "g8e.operator.v1.CommandRequested",`)
	assert.Contains(t, entry, `Outcomes: []string{"OperatorCommandCompleted"},`)
	assert.NotContains(t, entry, "Reserved")
}

