"""Verify first-party source files carry BSL 1.1 license headers."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SKIP_DIRS = {
    ".git",
    ".g8e",
    ".local.dev",
    ".pytest_cache",
    ".venv",
    "__pycache__",
    "build",
    "coverage",
    "dist",
    "node_modules",
    "third_party",
    "vendor",
}

SOURCE_EXTS = {".go", ".py", ".js", ".ts", ".tsx", ".proto", ".sh"}
SPECIAL_FILES = {"Dockerfile", "Makefile"}

SKIP_PATH_SUBSTRINGS = (
    "/site/assets/",
    "/static/assets/",
    ".min.js",
    ".min.css",
    "/vendor/",
    "package-lock.json",
)

GENERATED_PREFIXES = (
    "// Code generated by protoc-gen-go",
    "# Code generated by protoc",
    "# Generated by the protocol buffer compiler",
    "# NO CHECKED-IN PROTOBUF GENCODE",
)


def should_check(path: Path) -> bool:
    if set(path.parts) & SKIP_DIRS:
        return False
    rendered = str(path)
    if any(substr in rendered for substr in SKIP_PATH_SUBSTRINGS):
        return False
    if path.name in SPECIAL_FILES:
        return True
    return path.suffix in SOURCE_EXTS


def is_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:10])
    return any(prefix in head for prefix in GENERATED_PREFIXES)


def has_bsl_header(text: str) -> bool:
    head = "\n".join(text.splitlines()[:12])
    return "Business Source License" in head or "BSL 1.1" in head


def find_missing(root: Path) -> list[Path]:
    missing: list[Path] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or not should_check(path):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if is_generated(text):
            continue
        if not has_bsl_header(text):
            missing.append(path)
    return missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="Repository root to scan (default: g8e repo root)",
    )
    args = parser.parse_args()

    missing = find_missing(args.root.resolve())
    if missing:
        print("ERROR: first-party source files missing BSL 1.1 headers:", file=sys.stderr)
        for path in missing:
            print(f"  {path.relative_to(args.root)}", file=sys.stderr)
        return 1

    print("BSL header check OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
