class TestDiskSpacePreflight:
    def test_check_disk_space_passes_when_sufficient(self, tmp_path: Path):
        """check_disk_space passes when available space exceeds the threshold."""
        check_disk_space(tmp_path, min_bytes=1)

    def test_check_disk_space_fails_when_insufficient(self, tmp_path: Path):
        """check_disk_space raises DiskSpacePreflightError when available space is below the threshold."""
        with patch("g8e_evals.runner.shutil.disk_usage") as mock_usage:
            mock_usage.return_value = type("usage", (), {"free": 0})()
            with pytest.raises(DiskSpacePreflightError):
                check_disk_space(tmp_path, min_bytes=1_000_000_000)

    def test_check_disk_space_error_carries_path_and_threshold(self, tmp_path: Path):
        """DiskSpacePreflightError carries the path and threshold in its message."""
        with patch("g8e_evals.runner.shutil.disk_usage") as mock_usage:
            mock_usage.return_value = type("usage", (), {"free": 0})()
            with pytest.raises(DiskSpacePreflightError) as exc_info:
                check_disk_space(tmp_path, min_bytes=1_000_000_000)
            assert str(tmp_path) in str(exc_info.value)
            assert "1000000000" in str(exc_info.value)

    def test_check_disk_space_zero_threshold_always_passes(self, tmp_path: Path):
        """check_disk_space with a zero threshold always passes."""
        check_disk_space(tmp_path, min_bytes=0)
